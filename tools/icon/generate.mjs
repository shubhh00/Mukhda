// Generates Mukhda's app icon: मुखड़ा in Yatra One, marigold with a thin ink outline, over a
// double rule, on the stage's curtain red with thin dark pinstripes (the game screen's colours).
//   app/src/main/res/drawable/ic_launcher_background.xml  (adaptive icon background: flat curtain red)
//   app/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive icon foreground: the outlined name)
//   app/src/main/res/drawable/ic_launcher_monochrome.xml  (themed icons: the name alone, no outline)
//   app/src/main/ic_launcher-playstore.png                 (512 px Play Store icon)
// Text is shaped with HarfBuzz so the Devanagari matra and nukta sit right, then turned into
// outline paths, because vector drawables can't hold text. The font lives here, not in the app,
// which no longer uses it. Run: npm install && npm run generate
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { Resvg } from "@resvg/resvg-js";

const require = createRequire(import.meta.url);
const hb = await require("harfbuzzjs");

const APP = path.resolve(import.meta.dirname, "..", "..", "app", "src", "main");
const FONT = path.join(import.meta.dirname, "fonts", "yatra_one.ttf");
const WORD = "मुखड़ा";

// The app's tokens (ui/theme/Color.kt).
const MARIGOLD = "#F5C02A";
const INK = "#1B1A17";
const CURTAIN_RED = "#861A1C";
/** Thin pinstripes over the red, a shade darker. */
const PINSTRIPE = "#6A1215";
const PINSTRIPE_WIDTH = 0.7;
const PINSTRIPE_GAP = 4;

/** The outline: drawn under the fill, so half its width shows outside the letters. */
const OUTLINE = 1.9;
// Launchers may crop the 108-unit icon to a circle of radius 33 around the centre.
const SAFE_RADIUS = 33;
// The word and its thick-and-thin double rule, centred together.
const BOX = { maxW: 53, maxH: 25, cx: 54, cy: 53 };
const RULES = [
  { x: 32, y: 68, w: 44, h: 2.4 },
  { x: 36, y: 72.5, w: 36, h: 1.2 },
];
/** The part of the canvas launchers show (they keep the middle 72 units, give or take). */
const PLAY_STORE_VIEW = "16 16 76 76";

function shape(fontFile, text) {
  const face = hb.createFace(hb.createBlob(fs.readFileSync(fontFile)), 0);
  const font = hb.createFont(face);
  const buffer = hb.createBuffer();
  buffer.addText(text);
  buffer.guessSegmentProperties();
  hb.shape(font, buffer);
  const commands = [];
  let pen = 0;
  for (const g of buffer.json()) {
    for (const m of font.glyphToPath(g.g).matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
      const nums = m[2].trim() ? m[2].trim().split(/[ ,]+/).map(Number) : [];
      const pts = [];
      for (let i = 0; i < nums.length; i += 2) pts.push(nums[i] + pen + g.dx, nums[i + 1] + g.dy);
      commands.push([m[1], ...pts]);
    }
    pen += g.ax;
  }
  return commands;
}

/** Scales the outlines into the box, centred, flipping y (fonts are y-up). Returns path data. */
function fit(commands, { maxW, maxH, cx, cy }) {
  const xs = [], ys = [];
  for (const [, ...p] of commands) for (let i = 0; i < p.length; i += 2) { xs.push(p[i]); ys.push(p[i + 1]); }
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const s = Math.min(maxW / (maxX - minX), maxH / (maxY - minY));
  const w = (maxX - minX) * s + OUTLINE, h = (maxY - minY) * s + OUTLINE;
  const corner = Math.max(
    Math.hypot(w / 2, h / 2 + Math.abs(cy - 54)),
    ...RULES.map((r) => Math.hypot(r.w / 2 + OUTLINE / 2, r.y + r.h + OUTLINE / 2 - 54)),
  );
  if (corner > SAFE_RADIUS) throw new Error(`the name reaches ${corner.toFixed(1)} from the centre; the safe radius is ${SAFE_RADIUS}`);
  const f = (n) => Number(n.toFixed(2));
  return commands.map(([cmd, ...p]) => {
    const pts = [];
    for (let i = 0; i < p.length; i += 2) {
      pts.push(`${f(cx + (p[i] - (minX + maxX) / 2) * s)},${f(cy - (p[i + 1] - (minY + maxY) / 2) * s)}`);
    }
    return cmd + pts.join(" ");
  }).join("");
}

const rect = (x, y, w, h) => `M${x},${y}h${w}v${h}h${-w}z`;
const lettering = fit(shape(FONT, WORD), BOX) + RULES.map((r) => rect(r.x, r.y, r.w, r.h)).join("");

/** A layer: a fill colour, path data, and optionally an outline drawn with it. */
const pinstripes = [];
for (let x = PINSTRIPE_GAP / 2; x < 108; x += PINSTRIPE_GAP) pinstripes.push(rect(x, 0, PINSTRIPE_WIDTH, 108));
const background = [
  { fill: CURTAIN_RED, d: rect(0, 0, 108, 108) },
  { fill: PINSTRIPE, d: pinstripes.join("") },
];
const foreground = [
  { fill: INK, d: lettering, stroke: INK, strokeWidth: OUTLINE },
  { fill: MARIGOLD, d: lettering },
];
const monochrome = [{ fill: INK, d: lettering }];

const vector = (comment, layers) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment} Generated by tools/icon; edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${layers
  .map(({ fill, d, stroke, strokeWidth }) => {
    const outline = stroke ? `\n        android:strokeColor="#FF${stroke.slice(1)}"\n        android:strokeWidth="${strokeWidth}"\n        android:strokeLineJoin="round"` : "";
    return `    <path\n        android:fillColor="#FF${fill.slice(1)}"${outline}\n        android:pathData="${d}" />`;
  })
  .join("\n")}
</vector>
`;

const drawable = path.join(APP, "res", "drawable");
fs.writeFileSync(path.join(drawable, "ic_launcher_background.xml"), vector("App icon background: the curtain red with dark pinstripes.", background));
fs.writeFileSync(path.join(drawable, "ic_launcher_foreground.xml"), vector(`App icon: ${WORD} in Yatra One, outlined, over a double rule.`, foreground));
fs.writeFileSync(path.join(drawable, "ic_launcher_monochrome.xml"), vector(`Themed app icon: ${WORD} over a double rule.`, monochrome));

// The Play Store shows the icon as phones do, not the full 108-unit canvas a launcher crops.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${PLAY_STORE_VIEW}">${[...background, ...foreground]
  .map(({ fill, d, stroke, strokeWidth }) =>
    `<path fill="${fill}" d="${d}"${stroke ? ` stroke="${stroke}" stroke-width="${strokeWidth}" stroke-linejoin="round"` : ""}/>`)
  .join("")}</svg>`;
fs.writeFileSync(path.join(APP, "ic_launcher-playstore.png"), new Resvg(svg, { fitTo: { mode: "width", value: 512 } }).render().asPng());
console.log("Wrote ic_launcher_background.xml, ic_launcher_foreground.xml, ic_launcher_monochrome.xml and ic_launcher-playstore.png");
