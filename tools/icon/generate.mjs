// Generates Mukhda's app icon from the bundled Yatra One font:
//   app/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive icon foreground + monochrome)
//   app/src/main/ic_launcher-playstore.png                 (512 px Play Store icon)
// Text is shaped with HarfBuzz so the Devanagari matra and nukta sit right, then turned into
// outline paths, because vector drawables can't hold text. Run: npm install && npm run generate
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { Resvg } from "@resvg/resvg-js";

const require = createRequire(import.meta.url);
const hb = await require("harfbuzzjs");

const APP = path.resolve(import.meta.dirname, "..", "..", "app", "src", "main");
const WORD = "मुखड़ा";
const SAFFRON = "#F6B21A";
const MAROON_BAND = "#7A1027";
// Launchers may crop the 108-unit icon to a circle of radius 33 around the centre.
const SAFE_RADIUS = 33;
// The word and its thick-and-thin double rule are centred as one group.
const BOX = { maxW: 56, maxH: 28, cx: 54, cy: 51.5 };
const RULES = [
  { x: 30, y: 66, w: 48, h: 2.4 },
  { x: 34, y: 70.5, w: 40, h: 1.2 },
];

function shape(fontFile, text) {
  const face = hb.createFace(hb.createBlob(fs.readFileSync(fontFile)), 0);
  const font = hb.createFont(face);
  const buffer = hb.createBuffer();
  buffer.addText(text);
  buffer.guessSegmentProperties();
  hb.shape(font, buffer);
  const commands = [];
  let pen = 0;
  for (const g of buffer.json()) {
    for (const m of font.glyphToPath(g.g).matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
      const nums = m[2].trim() ? m[2].trim().split(/[ ,]+/).map(Number) : [];
      const pts = [];
      for (let i = 0; i < nums.length; i += 2) pts.push(nums[i] + pen + g.dx, nums[i + 1] + g.dy);
      commands.push([m[1], ...pts]);
    }
    pen += g.ax;
  }
  return commands;
}

/** Scales the outlines into the box, centred, flipping y (fonts are y-up). Returns path data. */
function fit(commands, { maxW, maxH, cx, cy }) {
  const xs = [], ys = [];
  for (const [, ...p] of commands) for (let i = 0; i < p.length; i += 2) { xs.push(p[i]); ys.push(p[i + 1]); }
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const s = Math.min(maxW / (maxX - minX), maxH / (maxY - minY));
  const w = (maxX - minX) * s, h = (maxY - minY) * s;
  const corner = Math.max(Math.hypot(w / 2, h / 2 + Math.abs(cy - 54)), ...RULES.map((r) => Math.hypot(r.w / 2, r.y + r.h - 54)));
  if (corner > SAFE_RADIUS) throw new Error(`text reaches ${corner.toFixed(1)} from the centre; the safe radius is ${SAFE_RADIUS}`);
  const f = (n) => Number(n.toFixed(2));
  return commands.map(([cmd, ...p]) => {
    const pts = [];
    for (let i = 0; i < p.length; i += 2) {
      pts.push(`${f(cx + (p[i] - (minX + maxX) / 2) * s)},${f(cy - (p[i + 1] - (minY + maxY) / 2) * s)}`);
    }
    return cmd + pts.join(" ");
  }).join("");
}

const data = fit(shape(path.join(APP, "res", "font", "yatra_one.ttf"), WORD), BOX);
const rules = RULES.map((r) => `M${r.x},${r.y}h${r.w}v${r.h}h${-r.w}z`).join("");

fs.writeFileSync(path.join(APP, "res", "drawable", "ic_launcher_foreground.xml"), `<?xml version="1.0" encoding="utf-8"?>
<!-- App icon: ${WORD} in Yatra One over a double rule. Generated by tools/icon; edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FF${SAFFRON.slice(1)}" android:pathData="${data}" />
    <path android:fillColor="#FF${SAFFRON.slice(1)}" android:pathData="${rules}" />
</vector>
`);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" fill="${MAROON_BAND}"/><path fill="${SAFFRON}" d="${data}"/><path fill="${SAFFRON}" d="${rules}"/></svg>`;
const png = new Resvg(svg, { fitTo: { mode: "width", value: 512 } }).render().asPng();
fs.writeFileSync(path.join(APP, "ic_launcher-playstore.png"), png);
console.log("Wrote ic_launcher_foreground.xml and ic_launcher-playstore.png");
